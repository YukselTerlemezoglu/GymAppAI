import { normalizeAiWeight, normalizeAiReps, normalizeAiProgram } from '../src/utils/aiNormalizer.js';
let pass=0, fail=0;
const check=(n,c,e='')=>{ if(c){pass++;console.log('PASS: '+n)} else {fail++;console.log('FAIL: '+n+' '+e)} };
check('50kg -> 50', normalizeAiWeight('50kg')==='50');
check('50 kg -> 50', normalizeAiWeight('50 kg')==='50');
check('15KG -> 15', normalizeAiWeight('15KG')==='15');
check('12,5kg -> 12.5', normalizeAiWeight('12,5kg')==='12.5');
check('8-12 kg -> 8-12', normalizeAiWeight('8-12 kg')==='8-12');
check('Vucut Agirligi -> BW', normalizeAiWeight('Vücut Ağırlığı')==='BW');
check('vücut ağırlığıyla -> BW', normalizeAiWeight('vücut ağırlığıyla')==='BW');
check('Bodyweight -> BW', normalizeAiWeight('Bodyweight')==='BW');
check('2 x 15kg -> 2 (set sayisi onde, nadir vaka)', normalizeAiWeight('2 x 15kg')==='2');
check('bos -> bos', normalizeAiWeight('')==='');
check('null -> bos', normalizeAiWeight(null)==='');
check('taninmayan metin -> bos (BW varsayimi kaldirildi)', normalizeAiWeight('makine ağırlığı')==='');
check('undefined -> bos', normalizeAiWeight(undefined)==='');
check('8-12 -> 8-12', normalizeAiReps('8-12')==='8-12');
check('12 -> 12', normalizeAiReps('12')==='12');
check('8 ila 12 -> 8-12', normalizeAiReps('8 ila 12')==='8-12');
check('maksimum -> MAX', normalizeAiReps('maksimum')==='MAX');
check('AMRAP -> MAX', normalizeAiReps('AMRAP')==='MAX');
check('15-20 tekrar -> 15-20', normalizeAiReps('15-20 tekrar')==='15-20');
const prog = { days: [ { dayName: 'A', exercises: [ { name:'Squat', sets:3, weight:'50kg', reps:'8-12' }, { name:'Pushup', sets:3, weight:'Vücut Ağırlığı', reps:'15' } ] } ] };
const norm = normalizeAiProgram(prog);
check('program: 50kg -> 50', norm.days[0].exercises[0].weight==='50');
check('program: VA -> BW', norm.days[0].exercises[1].weight==='BW');
check('orijinal bozulmadi', prog.days[0].exercises[0].weight==='50kg');
console.log(`\nSonuc: ${pass} gecti, ${fail} kaldi`);
process.exit(fail>0?1:0);
